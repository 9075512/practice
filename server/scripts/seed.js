function insertDemo() {
  const now = nowSql();
  let questionCount = 0;

  tx(() => {
    DEMO.forEach((bank, bankIndex) => {
      const inserted = run(
        'INSERT INTO bank (name, description, sort_order, created_at, updated_at) VALUES (?, ?, ?, ?, ?)',
        [bank.name, bank.description, bankIndex, now, now]
      );

      bank.questions.forEach((item, index) => {
        const [type, stem, optionTexts, answer, analysis] = item;
        const options = type === '判断题'
          ? [{ key: 'A', text: '正确' }, { key: 'B', text: '错误' }]
          : ['A', 'B', 'C', 'D'].slice(0, optionTexts.length).map((key, i) => ({
              key,
              text: optionTexts[i]
            }));

        run(
          `INSERT INTO question (bank_id, type, stem, options, answer, analysis, sort_order, created_at, updated_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          [inserted.lastInsertRowid, type, stem, JSON.stringify(options), answer, analysis, index, now, now]
        );
        questionCount += 1;
      });
    });
  });

  return questionCount;
}

const existing = Number(get('SELECT COUNT(*) AS count FROM question').count);

if (existing > 0 && !reset && !force) {
  console.log(`[seed] 已有 ${existing} 道题目，跳过。需要重灌请执行 npm run db:reset`);
  close();
  process.exit(0);
}

if (reset) {
  tx(() => {
    run('DELETE FROM question');
    run('DELETE FROM bank');
  });
  console.log('[seed] 已清空题库与题目');
}

if (process.argv.includes('--no-demo')) {
  console.log('[seed] 未写入示例数据（--no-demo）');
  close();
  process.exit(0);
}

const created = insertDemo();
console.log(`[seed] 已写入 ${DEMO.length} 个题库、${created} 道示例题`);
console.log('[seed] 清空示例数据：npm run db:reset');
close();
